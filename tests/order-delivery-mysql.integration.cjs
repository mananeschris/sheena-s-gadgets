const test = require('node:test');
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const mysql = require('mysql2');
const express = require('express');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const sharp = require('sharp');
const bcrypt = require('bcrypt');
const authRouter = require('../routes/auth');
const proofDirectory = process.env.RUN_DELIVERY_MYSQL === '1' ? fs.mkdtempSync(path.join(os.tmpdir(), 'delivery-proof-test-')) : path.join(os.tmpdir(), 'unused-delivery-test');
process.env.DELIVERY_PROOF_DIR = proofDirectory;
const { riderRouter, ensureDeliveryAssignmentsTable } = require('../routes/riders');
const adminRouter = require('../routes/riders');
const { query, issueSession } = require('../routes/chatSession');
const { attachOrderDeliveryDetails } = require('../routes/orderDeliveryDetails');

test('rider transition persists out-for-delivery timestamp and customer tracking history', { skip: process.env.RUN_DELIVERY_MYSQL !== '1' }, async t => {
  const database = `delivery_test_${crypto.randomBytes(8).toString('hex')}`;
  t.after(() => fs.rmSync(proofDirectory, { recursive: true, force: true }));
  const db = mysql.createConnection({ host: process.env.DB_HOST || '127.0.0.1', port: Number(process.env.DB_PORT || 3307), user: process.env.DB_USER || 'root', password: process.env.DB_PASSWORD || '' });
  await query(db, `CREATE DATABASE \`${database}\``);
  t.after(async () => {
    assert.match(database, /^delivery_test_[a-f0-9]{16}$/);
    await query(db, `DROP DATABASE \`${database}\``);
    await new Promise(resolve => db.end(resolve));
  });
  await query(db, `USE \`${database}\``);
  await query(db, 'CREATE TABLE users (id INT PRIMARY KEY, name VARCHAR(255), email VARCHAR(255), role VARCHAR(40))');
  await query(db, 'CREATE TABLE orders (id INT PRIMARY KEY, product_id INT, status VARCHAR(40), user_id INT, recipient_name VARCHAR(255), delivery_contact VARCHAR(80), delivery_address TEXT, processing_at DATETIME, shipped_at DATETIME, delivered_at DATETIME, warranty_expires_at DATETIME)');
  await query(db, 'CREATE TABLE products (id INT PRIMARY KEY, name VARCHAR(255))');
  await query(db, "INSERT INTO products VALUES (51,'Test Phone')");
  await query(db, "INSERT INTO users VALUES (201,'Test Rider','rider@example.com','rider')");
  await query(db, "INSERT INTO users VALUES (202,'Admin','admin@example.com','admin'), (203,'Other Rider','other@example.com','rider'), (204,'Customer','customer@example.com','customer')");
  await query(db, 'ALTER TABLE users ADD COLUMN password VARCHAR(255)');
  await query(db, 'UPDATE users SET password=? WHERE id=201', [await bcrypt.hash('CorrectPassword!1', 4)]);
  const cookies = {};
  for (const id of [201,202,203,204]) {
    const role = id === 202 ? 'admin' : id === 204 ? 'customer' : 'rider';
    await issueSession({ db, headers: {} }, { clearCookie() {}, cookie(name, token) { cookies[id] = `${name}=${token}`; } }, { id, role }, { adminVerified: role === 'admin' });
  }
  await query(db, "INSERT INTO orders (id,product_id,status,shipped_at) VALUES (34,51,'shipped',NOW())");
  await ensureDeliveryAssignmentsTable(db);
  await query(db, "INSERT INTO delivery_assignments (id,order_id,rider_id,status) VALUES (5,34,201,'assigned')");
  const app = express();
  app.use(express.json());
  app.use((req, res, next) => { req.db = db; next(); });
  app.use('/rider', riderRouter);
  app.use('/admin/riders', adminRouter);
  app.use('/auth', authRouter);
  const server = await new Promise(resolve => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)); });
  t.after(() => new Promise(resolve => server.close(resolve)));
  const url = `http://127.0.0.1:${server.address().port}/rider/assignments/5/status`;
  const update = status => fetch(url, { method: 'PUT', headers: { 'Content-Type': 'application/json', Cookie: cookies[201] }, body: JSON.stringify({ actor_id: 201, status, note: '' }) });
  const read = async () => {
    const orders = await query(db, 'SELECT * FROM orders WHERE id=34');
    return new Promise((resolve, reject) => attachOrderDeliveryDetails(db, orders, (err, rows) => err ? reject(err) : resolve(rows[0])));
  };
  assert.equal((await read()).delivery_status, 'assigned');
  assert.equal((await update('picked_up')).status, 200);
  assert.equal((await read()).delivery_status, 'picked_up');
  assert.equal((await read()).out_for_delivery_at, null);
  const outgoing = await update('out_for_delivery');
  assert.equal(outgoing.status, 200, await outgoing.text());
  const order = await read();
  assert.equal(order.status, 'shipped');
  assert.equal(order.delivery_status, 'out_for_delivery');
  assert.ok(order.out_for_delivery_at);
  const history = await query(db, "SELECT * FROM order_status_history WHERE order_id=34 AND status='out_for_delivery'");
  assert.equal(history.length, 1);
  assert.equal(history[0].actor_role, 'rider');
  assert.equal((await update('delivered')).status, 400);
  const origin = `http://127.0.0.1:${server.address().port}`;
  const signIn = password => fetch(`${origin}/auth/login`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ email: 'rider@example.com', password }) });
  assert.equal((await signIn('WrongPassword')).status, 400);
  const signedIn = await signIn('CorrectPassword!1');
  assert.equal(signedIn.status, 200, await signedIn.clone().text());
  assert.equal((await signedIn.json()).user.id, 201);
  const cookieHeader = signedIn.headers.getSetCookie().find(value => /^delivery_session=[a-f0-9]{64};/.test(value));
  assert.match(cookieHeader, /HttpOnly/i);
  cookies[201] = cookieHeader.split(';')[0];
  const photo = await sharp({ create: { width: 80, height: 60, channels: 3, background: '#a3b4c5' } }).jpeg().toBuffer();
  const upload = (buffer = photo, actor = 201, type = 'image/jpeg') => {
    const form = new FormData();
    if (buffer) form.append('delivery_proof', new Blob([buffer], { type }), 'delivery.jpg');
    return fetch(`${origin}/rider/assignments/5/delivery-proof`, { method: 'POST', headers: { 'X-Actor-Id': String(actor), Cookie: cookies[actor] }, body: form });
  };
  assert.equal((await fetch(`${origin}/rider/assignments/5/delivery-proof`, { method: 'POST', headers: { 'X-Actor-Id': '201' }, body: new FormData() })).status, 401);
  assert.equal((await fetch(`${origin}/rider/assignments/5/delivery-proof`, { method: 'POST', headers: { 'X-Actor-Id': '201', Cookie: cookies[203] }, body: new FormData() })).status, 401);
  assert.equal((await fetch(`${origin}/rider/assignments/5/delivery-proof`, { method: 'POST', headers: { 'X-Actor-Id': '201', Cookie: cookies[201], Origin: 'http://evil.example' }, body: new FormData() })).status, 403);
  assert.equal((await upload(null)).status, 400);
  assert.equal((await upload(Buffer.from('not a photo'))).status, 400);
  assert.equal((await upload(photo, 201, 'image/gif')).status, 400);
  assert.equal((await upload(Buffer.alloc(5 * 1024 * 1024 + 1))).status, 400);
  assert.equal((await upload(photo, 203)).status, 404);
  assert.equal((await upload(photo, 204)).status, 403);
  assert.equal((await read()).status, 'shipped');
  await query(db, "CREATE TRIGGER fail_delivery BEFORE UPDATE ON orders FOR EACH ROW BEGIN IF NEW.status='delivered' THEN SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT='Test rollback'; END IF; END");
  assert.equal((await upload()).status, 500);
  assert.equal((await read()).delivery_status, 'out_for_delivery');
  assert.equal(fs.readdirSync(proofDirectory).length, 0);
  await query(db, 'DROP TRIGGER fail_delivery');
  const deliveries = await Promise.all([upload(), upload()]);
  assert.deepEqual(deliveries.map(response => response.status).sort(), [200,400]);
  assert.equal((await read()).status, 'delivered');
  assert.equal((await read()).delivery_status, 'delivered');
  assert.equal((await upload()).status, 400);
  assert.equal(fs.readdirSync(proofDirectory).length, 1);
  const noticesUrl = `${origin}/admin/riders/delivery-notifications?actor_id=202`;
  const adminFetch = (url, options = {}) => fetch(url, { ...options, headers: { ...options.headers, Cookie: cookies[202] } });
  const notices = await (await adminFetch(noticesUrl)).json();
  assert.equal(notices.items.length, 1);
  assert.equal(notices.items[0].title, 'Test Phone: Delivered');
  assert.equal(notices.items[0].assignment_id, 5);
  const proofUrl = `${origin}/admin/riders/assignments/5/proof`;
  assert.equal((await fetch(`${proofUrl}?actor_id=202`)).status, 401);
  assert.equal((await fetch(`${proofUrl}?actor_id=202`, { headers: { Cookie: cookies[204] } })).status, 403);
  assert.equal((await fetch(`${proofUrl}?actor_id=201`, { headers: { Cookie: cookies[201] } })).status, 403);
  assert.equal((await adminFetch(`${proofUrl}?actor_id=204`)).status, 401);
  const proof = await adminFetch(`${proofUrl}?actor_id=202`);
  assert.equal(proof.status, 200);
  assert.match(proof.headers.get('content-type'), /image\/jpeg/);
  assert.equal(proof.headers.get('cache-control'), 'no-store');
  assert.equal((await sharp(Buffer.from(await proof.arrayBuffer())).metadata()).width, 80);
  assert.equal((await adminFetch(`${proofUrl}/seen`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ actor_id: 202 }) })).status, 200);
  assert.equal((await (await adminFetch(noticesUrl)).json()).items.length, 0);
  assert.equal((await adminFetch(`${proofUrl}?actor_id=202`)).status, 200);
  await query(db, "INSERT INTO orders (id,product_id,status) VALUES (35,51,'shipped'), (36,51,'pending')");
  const selfDelivery = order_id => adminFetch(`${origin}/admin/riders/self-delivery`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ actor_id: 202, order_id }) });
  assert.equal((await selfDelivery(36)).status, 400);
  const self = await selfDelivery(35);
  assert.equal(self.status, 200, await self.clone().text());
  const assignmentId = (await self.json()).assignment_id;
  assert.equal((await selfDelivery(35)).status, 400);
  const adminStatus = status => adminFetch(`${origin}/admin/riders/assignments/${assignmentId}/status`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ actor_id: 202, status }) });
  assert.equal((await adminStatus('out_for_delivery')).status, 200);
  assert.equal((await adminStatus('delivered')).status, 400);
  const adminForm = new FormData();
  adminForm.append('delivery_proof', new Blob([photo], { type: 'image/jpeg' }), 'admin-delivery.jpg');
  const adminDelivered = await adminFetch(`${origin}/admin/riders/assignments/${assignmentId}/delivery-proof`, { method: 'POST', headers: { 'X-Actor-Id': '202' }, body: adminForm });
  assert.equal(adminDelivered.status, 200, await adminDelivered.clone().text());
  const adminOrder = (await query(db, 'SELECT status FROM orders WHERE id=35'))[0];
  assert.equal(adminOrder.status, 'delivered');
  const adminHistory = await query(db, "SELECT actor_role FROM order_status_history WHERE order_id=35 AND status IN ('out_for_delivery', 'delivered')");
  assert.deepEqual(adminHistory.map(item => item.actor_role), ['admin', 'admin']);
  assert.equal((await adminFetch(`${origin}/admin/riders/assignments/${assignmentId}/proof?actor_id=202`)).status, 200);
  // Admin may also update an existing rider assignment without taking ownership.
  await query(db, "INSERT INTO orders (id,product_id,status) VALUES (37,51,'shipped')");
  await query(db, "INSERT INTO delivery_assignments (id,order_id,rider_id,status) VALUES (99,37,201,'assigned')");
  const adminUpdate = await adminFetch(`${origin}/admin/riders/assignments/99/status`, { method: 'PUT', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ actor_id: 202, status: 'out_for_delivery' }) });
  assert.equal(adminUpdate.status, 200);
  assert.equal((await query(db, 'SELECT rider_id FROM delivery_assignments WHERE id=99'))[0].rider_id, 201);
  assert.equal((await fetch(`${origin}/admin/riders/assignments/99/status`, { method: 'PUT', headers: { 'Content-Type': 'application/json', Cookie: cookies[204] }, body: JSON.stringify({ actor_id: 204, status: 'delivered' }) })).status, 403);
  await query(db, 'UPDATE delivery_chat_sessions SET expires_at=DATE_SUB(NOW(), INTERVAL 1 DAY) WHERE user_id=202');
  assert.equal((await adminFetch(`${proofUrl}?actor_id=202`)).status, 401);
});
